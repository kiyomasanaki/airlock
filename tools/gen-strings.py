#!/usr/bin/env python3
"""Generate js/banner-strings.js and js/worker-strings.js.

The reminder card (js/content.js) runs on every page the user visits, and the
service worker (js/background.js) can only import scripts when it starts: neither
can load js/locales/<code>.js on demand like the extension pages do. Each gets a
small file instead: the engine of js/i18n.js (between its @engine markers) plus,
for every language, only the keys that file really uses.

Keys are found from the calls `airlockT('key'...)`. The rule is strict: the first
argument must be a string literal, so no key can hide behind a variable, a
template or a ternary. Any other call stops the generator with a non-zero exit.

Standard library only. Run from anywhere: python3 tools/gen-strings.py
With --check, writes nothing and fails when a generated file is not up to date
(used by package.sh).
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import locales  # noqa: E402

ROOT = locales.ROOT
TARGETS = {
    "js/banner-strings.js": "js/content.js",
    "js/worker-strings.js": "js/background.js",
}
CALL = re.compile(r"\bairlockT\s*\(")
LITERAL = re.compile(r"""\s*(['"])([A-Za-z0-9_]+)\1\s*[,)]""")


def used_keys(rel, root=ROOT):
    """Keys of the literal airlockT calls in a source file; exits on any other call."""
    text = (root / rel).read_text(encoding="utf-8")
    keys, errors = [], []
    for m in CALL.finditer(text):
        line = text.count("\n", 0, m.start()) + 1
        lit = LITERAL.match(text, m.end())
        if not lit:
            end = text.find("\n", m.start())
            snippet = text[m.start():end if end != -1 else None].strip()
            errors.append(f"{rel}:{line}: airlockT must be called with a string literal key: {snippet}")
            continue
        if lit.group(2) not in keys:
            keys.append(lit.group(2))
    if errors:
        sys.exit("\n".join(errors))
    return keys


def engine():
    text = (ROOT / "js" / "i18n.js").read_text(encoding="utf-8")
    m = re.search(r"// @engine-start\n(.*?)// @engine-end\n", text, re.S)
    if not m:
        sys.exit("js/i18n.js: @engine-start / @engine-end markers not found")
    return m.group(1)


def build(source, keys, strings):
    missing = [k for k in keys if k not in strings["en"]]
    if missing:
        sys.exit(f"{source}: keys not in the English dictionary: {', '.join(missing)}")
    lines = [
        "// GENERATED by tools/gen-strings.py from js/i18n.js and js/locales/*.js: do not edit.",
        f"// The engine of js/i18n.js and only the keys used by {source}, for every language.",
        "",
        engine().rstrip(),
        "",
    ]
    for code in ["en"] + sorted(c for c in strings if c != "en"):
        subset = {k: strings[code][k] for k in keys if k in strings[code]}
        lines.append(f"airlockAddStrings({json.dumps(code)}, {json.dumps(subset, ensure_ascii=False)});")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    strings = locales.read_all()
    stale = []
    for target, source in TARGETS.items():
        keys = used_keys(source)
        out = build(source, keys, strings)
        path = ROOT / target
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != out:
                stale.append(target)
        else:
            path.write_text(out, encoding="utf-8")
            print(f"{target}: {len(strings)} languages, {len(keys)} keys")
    if stale:
        sys.exit("not up to date, run python3 tools/gen-strings.py: " + ", ".join(stale))


if __name__ == "__main__":
    main()
