const AIRLOCK_LANGS = Object.keys(AIRLOCK_LANG_META);
const AIRLOCK_RTL = ['ar', 'ur'];
// cached in the extension's own localStorage so pages paint in the right
// language at once (same trick as js/theme.js); never the web page's storage
const AIRLOCK_LANG_CACHE = 'airlock_lang_resolved';
const AIRLOCK_EXT_PAGE = typeof location !== 'undefined' && location.protocol === 'chrome-extension:'
  && typeof document !== 'undefined';
const AIRLOCK_STRINGS = {};

function airlockAddStrings(code, dict) {
  AIRLOCK_STRINGS[code] = dict;
}

function airlockResolveLang(pref) {
  if (AIRLOCK_LANGS.includes(pref)) return pref;
  const nav = ((typeof navigator !== 'undefined' && navigator.language) || '').toLowerCase();
  if (/^pt\b/.test(nav)) return 'pt-BR';
  if (/^zh\b/.test(nav)) return 'zh-CN';
  const base = nav.split('-')[0];
  return AIRLOCK_LANGS.includes(base) ? base : 'en';
}

function airlockCachedLang() {
  if (!AIRLOCK_EXT_PAGE) return null;
  try { return localStorage.getItem(AIRLOCK_LANG_CACHE); } catch (e) { return null; }
}

let airlockLang = airlockResolveLang(airlockCachedLang());

// Locale tag for dates, times and plural rules.
function airlockLocale(lang) {
  return AIRLOCK_LANG_META[lang || airlockLang].locale;
}

function airlockIsRtl(lang) {
  return AIRLOCK_RTL.includes(lang || airlockLang);
}

function airlockPlural(n, forms, lang) {
  let cat = 'other';
  try { cat = new Intl.PluralRules(airlockLocale(lang)).select(n); } catch (e) {}
  return forms[cat] != null ? forms[cat] : forms.other;
}

// airlockT('queueCount', 3) is short for airlockT('queueCount', { n: 3 }); plural
// forms are chosen on {n}, then every {placeholder} is filled.
function airlockT(key, vars) {
  const dict = AIRLOCK_STRINGS[airlockLang] || {};
  let v = dict[key];
  let lang = airlockLang;
  if (v == null) { v = AIRLOCK_STRINGS.en[key]; lang = 'en'; }
  if (v == null) return key;
  if (typeof vars === 'number') vars = { n: vars };
  if (Array.isArray(v)) v = v.join('\n');
  else if (typeof v === 'object') v = airlockPlural(vars && typeof vars.n === 'number' ? vars.n : 0, v, lang);
  return vars ? v.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : v;
}

// Sets the language from a stored preference. Returns true when it changed.
function airlockSetLang(pref) {
  const lang = airlockResolveLang(pref);
  const changed = lang !== airlockLang;
  airlockLang = lang;
  if (AIRLOCK_EXT_PAGE) {
    try { localStorage.setItem(AIRLOCK_LANG_CACHE, lang); } catch (e) {}
  }
  return changed;
}

// Loads js/locales/<code>.js once, on extension pages only. Elsewhere every
// string the surface needs is already bundled.
const airlockLoading = {};
function airlockLoadLang(code) {
  if (AIRLOCK_STRINGS[code] || !AIRLOCK_EXT_PAGE) return Promise.resolve();
  if (!airlockLoading[code]) {
    airlockLoading[code] = new Promise(resolve => {
      const s = document.createElement('script');
      s.src = chrome.runtime.getURL(`js/locales/${code}.js`);
      s.onload = s.onerror = () => resolve();
      document.head.appendChild(s);
    });
  }
  return airlockLoading[code];
}

// Fills the static text of an extension page from its data-i18n* attributes.
function airlockApplyI18n(root) {
  root.querySelectorAll('[data-i18n]').forEach(n => { n.textContent = airlockT(n.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach(n => { n.innerHTML = airlockT(n.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-title]').forEach(n => { n.title = airlockT(n.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(n => {
    n.placeholder = airlockT(n.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach(n => {
    n.setAttribute('aria-label', airlockT(n.dataset.i18nAriaLabel));
  });
  document.documentElement.lang = airlockLang;
  document.documentElement.dir = airlockIsRtl() ? 'rtl' : 'ltr';
}

function airlockUnveil() {
  if (AIRLOCK_EXT_PAGE) document.documentElement.classList.remove('airlock-i18n-pending');
}

// Extension pages load this file in <head>: when the cached language is not
// English, the page stays hidden until its strings are there (300 ms at most),
// so it never flashes English first.
if (AIRLOCK_EXT_PAGE && airlockLang !== 'en') {
  document.documentElement.classList.add('airlock-i18n-pending');
  airlockLoadLang(airlockLang);
  setTimeout(airlockUnveil, 300);
}

// For pages and the content script: `onReady` runs once the stored choice is
// known and its strings loaded, then again after every change of language.
function airlockI18nInit(onReady) {
  const apply = () => { if (AIRLOCK_EXT_PAGE) airlockApplyI18n(document); };
  airlockLoadLang(airlockLang).then(apply);
  chrome.storage.local.get([AIRLOCK_LANG_KEY], r => {
    airlockSetLang(r[AIRLOCK_LANG_KEY]);
    airlockLoadLang(airlockLang).then(() => { apply(); airlockUnveil(); onReady(); });
  });
  chrome.storage.onChanged.addListener((changes, area) => {
    if (area !== 'local' || !changes[AIRLOCK_LANG_KEY]) return;
    if (!airlockSetLang(changes[AIRLOCK_LANG_KEY].newValue)) return;
    const lang = airlockLang;
    airlockLoadLang(lang).then(() => {
      if (lang !== airlockLang) return;       // superseded by a newer choice
      apply();
      onReady();
    });
  });
}
