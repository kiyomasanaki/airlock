// Airlock - interface language, switchable live.
//
// chrome.i18n follows Chrome's own UI language and cannot be changed at
// runtime, so the interface uses this dictionary instead (chrome.i18n only
// localises the manifest: name, description, shortcut label).
//
// This file holds the engine, the table of the 20 languages and English, the
// fallback. Every other language lives in js/locales/<code>.js and extension
// pages load only the active one, again on every change. The reminder card and
// the service worker cannot load a file later: they get js/banner-strings.js
// and js/worker-strings.js instead, generated by tools/gen-strings.py from the
// engine below and the keys they actually use.
//
// The choice lives in chrome.storage.local under `airlock_lang` ('auto' or a
// code of AIRLOCK_LANGS), a UI preference like `airlock_ui`: never exported.
// Every surface listens to chrome.storage.onChanged and re-renders, so a change
// in the popup or the Options page reaches every other surface without a reload.
//
// Strings are plain data so Python can read them (tools/, docs/build.py): a
// value is a string with {placeholders}, an object of plural forms chosen by
// Intl.PluralRules on {n}, or an array of lines. Strings used with
// data-i18n-html are trusted markup from these files only: user data always
// goes through textContent.

